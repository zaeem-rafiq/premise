// Regenerates `src/worker/app-server/host-bundle.ts` from a fresh vite build of `src/host/`.
// Run: `node test/tidepool/host/update-host-bundle.ts` (Node strips types; nothing is compiled).

import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { promises as fs } from "node:fs";
import { format } from "prettier";
import { buildHostBundle } from "./bundle.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const { file, source, build } = await buildHostBundle(root);
const out =
  `// GENERATED by test/tidepool/host/update-host-bundle.ts — do not edit by hand.\n` +
  `//\n` +
  `// The pool host bundle, as \"vite build --config vite.host.config.ts\" emits it at\n` +
  `// dist/client/pool/${file}.\n` +
  `//\n` +
  `// Why it is committed: \"~boot.js\" must name \"~host.<build>.js\" in generated code, but the\n` +
  `// worker has no runtime way to learn vite's content hash — dist/meta is not deployed and the\n` +
  `// ASSETS binding cannot list directories. So the bundle text travels with the worker:\n` +
  `// \"~host.<build>.js\" serves this string, with <build> = the first ${build.length} hex chars of its\n` +
  `// sha-256. host-bundle.test.ts fails when the two builds drift apart.\n` +
  `\n` +
  `export const HOST_BUILD = ${JSON.stringify(build)};\n` +
  `\n` +
  `export const HOST_SOURCE = ${JSON.stringify(source)};\n`;
await fs.writeFile(
  join(root, "src/worker/app-server/host-bundle.ts"),
  await format(out, { parser: "typescript" }), // `npm run check` runs prettier --check
);
console.log(`host-bundle.ts updated: ~host.${build}.js (${source.length} bytes, vite name ${file})`);
